const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { Prisma } = require('@prisma/client');
const { captureMarketCatalogCards, hydrateMarketCatalogCards } = require('../../src/market/catalog/market-catalog-cards');
const { captureMarketCatalogCardsBatched } = require('../../src/market/catalog/market-catalog-card-batch');
const {runMarketCatalogMediaAssociationAssertions}=require('./market-catalog-media-association-assertions.cjs');
const {runMarketSourceKeysetAssertions}=require('./market-source-keyset-assertions.cjs');

async function runMarketCatalogBatchAssertions({db,prisma,now,queryCount,queryStats,chosen,owner,brand,category,firstFile,backFile,config}){
  assert(/^aru_market_pipeline_[a-f0-9]{32}$/.test(db.connectionParameters.database));
  let checks=0;
  const equal=(actual,expected,label)=>{assert.deepEqual(actual,expected,label);checks++;};
  const input={rows:[{id:chosen.id,amount:new Prisma.Decimal(9000)}],asOf:now};
  const uploads={getBatchPublicSignedUrls:async ids=>new Map(ids.map(id=>[id,'https://gateway.fixture.invalid/by-id/'+id])),getBatchVariantDisplayUrls:async()=>new Map()};
  const pair=async(label)=>{
    const old=await captureMarketCatalogCards(prisma,input);
    const before=queryCount();
    const batched=await captureMarketCatalogCardsBatched(prisma,input);
    equal(queryCount()-before,1,label+' uses one actual PostgreSQL data statement');
    equal(batched.map(card=>card.product.id),old.map(card=>card.product.id),label+' keeps the same product authority');
    equal(await hydrateMarketCatalogCards(batched,uploads),await hydrateMarketCatalogCards(old,uploads),label+' preserves every rendered public card field');
    equal(batched.map(card=>card.file.id),old.map(card=>card.file.id),label+' preserves current cover identity');
    equal(batched.map(card=>card.logoFileId),old.map(card=>card.logoFileId),label+' preserves current owner logo identity');
    return {old,batched};
  };
  assert.equal(typeof queryCount,'function','Fixture must instrument actual Prisma query events');
  const initial=await pair('Original approved gallery');
  equal(initial.batched[0].product.media.map(row=>row.file.id),[firstFile.id,backFile.id],'Batch retains both approved gallery views');
  equal(initial.batched[0].product.price instanceof Prisma.Decimal,true,'Batch restores money strings to Prisma Decimal');
  equal(initial.batched[0].product.createdAt instanceof Date,true,'Batch restores UTC JSON dates to Date');
  equal(initial.batched[0].asOf.getTime(),now.getTime(),'Batch preserves captured pricing time');
  const leaked=JSON.stringify(initial.batched);
  equal(leaked.includes('PRIVATE PROFILE SENTINEL')||leaked.includes('PRIVATE PHONE SENTINEL'),false,'Batch contains no private owner profile fields');
  const logo=await prisma.fileUpload.create({data:{id:randomUUID(),userId:owner.id,originalName:'Logo',fileName:'logo.webp',s3Key:'scope/logo.webp',s3Url:'https://private.fixture.invalid/scope-logo.webp',fileType:'PROFILE_IMAGE',mimeType:'image/webp',size:100,processingStatus:'READY',assetVersion:1}});
  await prisma.userProfile.create({data:{userId:owner.id,profileImageId:logo.id,firstName:'PRIVATE PROFILE SENTINEL',lastName:'PRIVATE FAMILY SENTINEL',phoneNumber:'PRIVATE PHONE SENTINEL'}});
  await prisma.brand.update({where:{id:brand.id},data:{logo:logo.s3Url}});
  const withLogo=await pair('Current linked owner profile logo');
  equal(withLogo.batched[0].logoFileId,logo.id,'Actual linked profile authorizes the logo');
  await prisma.userProfile.update({where:{userId:owner.id},data:{profileImageId:null}});
  const removedLogo=await pair('Removed profile logo association');
  equal(removedLogo.batched[0].logoFileId,null,'Brand URL alone cannot authorize a removed profile logo');
  await prisma.userProfile.update({where:{userId:owner.id},data:{profileImageId:logo.id}});
  const variant=await prisma.fileVariant.create({data:{id:randomUUID(),fileUploadId:firstFile.id,variantKind:'CARD',format:'WEBP',width:300,height:450,sizeBytes:100,quality:95,s3Key:'scope/front-card.webp',s3Url:'https://private.fixture.invalid/scope-front-card.webp',assetVersion:1}});
  await prisma.product.update({where:{id:chosen.id},data:{thumbnail:variant.s3Url}});
  equal((await pair('Current-version processed cover')).batched[0].file.id,firstFile.id,'Current processed cover resolves to its managed original');
  await prisma.fileUpload.update({where:{id:firstFile.id},data:{assetVersion:2}});
  equal((await pair('Stale-version processed cover')).batched.length,0,'Stale processed variant never authorizes a new original version');
  await prisma.fileUpload.update({where:{id:firstFile.id},data:{assetVersion:1}});
  const front=await prisma.productMedia.findFirst({where:{productId:chosen.id,fileUploadId:firstFile.id}});
  await prisma.productMedia.update({where:{id:front.id},data:{reviewStatus:'CHANGES_REQUESTED'}});
  equal((await pair('Unapproved cover')).batched.length,0,'A denied media association removes the card');
  await prisma.productMedia.update({where:{id:front.id},data:{reviewStatus:'APPROVED'}});
  await prisma.product.update({where:{id:chosen.id},data:{publicationStatus:'DRAFT'}});
  equal((await pair('Draft parent')).batched.length,0,'Neither capture permits an active draft');
  await prisma.product.update({where:{id:chosen.id},data:{publicationStatus:'PUBLISHED'}});
  await prisma.collectionCategory.update({where:{id:category.id},data:{isActive:false}});
  const inactive=await pair('Inactive taxonomy');
  equal((await hydrateMarketCatalogCards(inactive.batched,uploads))[0].category,null,'Inactive category metadata stays out of public cards');
  await prisma.collectionCategory.update({where:{id:category.id},data:{isActive:true}});
  const privateCollection=await prisma.storeCollection.create({data:{id:randomUUID(),ownerId:owner.id,title:'PRIVATE LOOK SENTINEL',description:'PRIVATE LOOK DESCRIPTION SENTINEL',status:'PUBLISHED',visibility:'PRIVATE',isAvailableInStore:true}});
  const publicCollection=await prisma.storeCollection.create({data:{id:randomUUID(),ownerId:owner.id,title:'Public proof',status:'PUBLISHED',visibility:'PUBLIC',isAvailableInStore:true}});
  await prisma.storeCollectionProduct.createMany({data:[privateCollection,publicCollection].map(collection=>({id:randomUUID(),collectionId:collection.id,productId:chosen.id}))});
  const mixed=await pair('Mixed public/private membership proof');
  equal(mixed.batched[0].product.collections.length,1,'Batch retains bounded membership authority');
  equal(JSON.stringify(await hydrateMarketCatalogCards(mixed.batched,uploads)).includes('PRIVATE LOOK'),false,'Private membership metadata never appears in a public card');
  let emptyReads=0;
  equal(await captureMarketCatalogCardsBatched({$queryRaw:async()=>{emptyReads++;return[];}},{rows:[],asOf:now}),[],'Empty capture stays empty');
  equal(emptyReads,0,'Empty capture acquires no database data read');
  await prisma.product.update({where:{id:chosen.id},data:{thumbnail:firstFile.s3Url}});
  const associations=await runMarketCatalogMediaAssociationAssertions({db,prisma,chosen,owner,brand,firstFile,backFile,config});
  checks+=associations.checks;
  const keysets=await runMarketSourceKeysetAssertions({db,prisma,now,brand,owner,chosen,firstFile,queryStats,config});
  checks+=keysets.checks;
  console.log(`PASS ${checks} catalogue batched projection/authority/physical-query proofs`);
  return {checks};
}
module.exports={runMarketCatalogBatchAssertions};
